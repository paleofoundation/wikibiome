const canonicalSlugPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export function articleMediaFileNames(pageId, assetType, revision) {
  if (!canonicalSlugPattern.test(pageId)) throw new Error(`Invalid canonical article slug: ${pageId}.`);
  if (!articleMediaPolicy.assetTypes.includes(assetType)) throw new Error(`Unsupported article media asset type: ${assetType}.`);
  if (!Number.isInteger(revision) || revision < 1) throw new Error(`Invalid article media revision for ${pageId}: ${revision}.`);
  const stem = `${pageId}-${assetType}-v${revision}`;
  const publishedFile = `${stem}.webp`;
  const socialFile = `${stem}-social.webp`;
  return Object.freeze({
    publishedFile,
    socialFile,
    src: `/media/image/${publishedFile}`,
    socialSrc: `/media/social/${socialFile}`,
    masterSource: `${stem}-master.png`,
  });
}

function defineArticleMedia(record) {
  const files = articleMediaFileNames(record.pageId, record.assetType, record.revision);
  return Object.freeze({
    ...common,
    ...record,
    ...files,
    reviewLogKey: `${record.pageId}|${files.publishedFile}`,
  });
}

